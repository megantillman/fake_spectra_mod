# Below are functions I use for comparing various statistics. 
# These are typically pulled from the master code but placed independently here usually for computation speed reasons.
def get_CDD(spectra, dLogN = 0.2,  minN = 11., maxN = 23., close = 50., dX = False, dlogn = True, line = False):
    
    '''
    This computes the absorber column density distribution function, which is the number
        of absorbers per sight line with column densities in the interval
        [N, N+dN] at the absorption distance X.
        The path can be either a whole sightline across the box, if line=True, or, if line=False,
        it can be a fixed spacing in the hubble flow.

        So we have f(N) = d n_abs/ dlogN dz by default
            with dlogN -> dN if dlogn = False
            with dz -> dX if dX = True

        Arguments:
            dlogN - bin spacing
            minN - minimum log N
            maxN - maximum log N
            close - amalgamate absorbers closer than X km/s
            dX - If true return dn/dlogN dX, if false return dn/dlogN dz
            dlogn - If true return dn/dlogN dz, if false return dn/dN dz
            line - cddf for whole line or for each cell.
        Returns:
            dlogN, f_N_table - N_HI (binned in log) and corresponding f(N)
    '''

    tot_lines = spectra.NumLos+spectra.discarded

    NHI_table = 10**np.arange(minN, maxN, dLogN)
    center = np.array([(NHI_table[i]+NHI_table[i+1])/2. for i in range(0, np.size(NHI_table)-1)])
    width = np.array([NHI_table[i+1]-NHI_table[i] for i in range(0, np.size(NHI_table)-1)])

    if line:
        cds = np.sum(spectra.get_col_density(elem="H", ion=1), axis=1)
    else:
        cds = spectra.get_col_density(elem="H", ion=1)
        cbins = np.max((int(np.round((close/spectra.dvbin))), 1))
        cdsb = np.array([np.sum(cds[:, cbins*i:cbins*(i+1)], axis=1) for i in range(int(np.shape(cds)[1]/cbins))]).T
        cds = cdsb
    
    if dlogn:
        div_width=dLogN
    else:
        div_width=width
        
    (tot_f_N, NHI_table) = np.histogram(cds, NHI_table) 
    
    if dX:
        dX=spectra.units.absorption_distance(spectra.box,spectra.red)
        tot_f_N = tot_f_N/(div_width*dX*tot_lines)
    else:
        dz = spectra.units.redshift_distance(spectra.box, spectra.red, spectra.OmegaM)
        tot_f_N = tot_f_N/(div_width*dz*tot_lines)
        
    return np.log10(center), tot_f_N


def get_voigt_CDD(spectra, elem="H", ion=1, line=1215, dLogN = 0.2, minN = 11., maxN = 23., close=0, dX=False, dlogn = True, nspectra=-1, snr=0, EMD=True):
    '''
    This computes the column density function using column densities from a Voigt profile fit.
    Concatenate objects closer than close km/s.

        Arguments:
            spectra - the loaded in spectra file generated by fake spectra
            elem - element to generate for
            ion - element ionization
            line - spectral line of interest
            dLogN - bin spacing
            minN - minimum log N
            maxN - maximum log N
            close - amalgamate absorbers closer than X km/s
            dX - If true return dn/dlogN dX, if false return dn/dlogN dz
            dlogn - If true return dn/dlogN dz, if false return dn/dN dz
            line - cddf for whole line or for each cell.
            snr - default is 0 or perfect SNR
        Returns:
            dlogN, f_N_table - N_HI (binned in log) and corresponding f(N)
            b and logN_HI - b-values and log column desntities from fits
            fit results - the resulting fits from the Voigt fitting
            tau - the optical depths that were fit
    '''

    NHI_table = 10**np.arange(minN, maxN, dLogN)
    center = np.array([(NHI_table[i]+NHI_table[i+1])/2. for i in range(0, np.size(NHI_table)-1)])
    width = np.array([NHI_table[i+1]-NHI_table[i] for i in range(0, np.size(NHI_table)-1)])
   
    tau = spectra.get_tau(elem, ion, line)

    if snr != 0:
        flux = np.exp(-tau)
        lines = np.shape(flux)[0]
        snr = np.zeros(np.shape(flux)[0]) + snr
        (flux_noise, noise) = spectra.add_noise(snr, flux)
        flux_noise[flux_noise > 1] = 1
        flux_noise[flux_noise < 0] = 0
        tau_noise = -np.log(flux_noise)
        tau = np.asarray(tau_noise)
        
    tau_filt = [tau_ind for tau_ind in tau if not (max(tau_ind) > 100)]
    tau = np.asarray(tau_filt)
        
    tot_lines = len(tau[:,0])

    n_vals, b_params, fit_results = voigtfit.get_voigt_fits_and_params(tau, spectra.dvbin, elem=elem, ion=ion, line=line, verbose=False, close=close, EMD=EMD)
    
    if dlogn:
        div_width=dLogN
    else:
        div_width=width
    
    (tot_f_N, NHI_table) = np.histogram(n_vals, NHI_table)
    
    #Absorption distance for each line
    if dX:
        dX=spectra.units.absorption_distance(spectra.box,spectra.red)
        tot_f_N = tot_f_N/(div_width*dX*tot_lines)
    else:
        dz = spectra.units.redshift_distance(spectra.box, spectra.red, spectra.OmegaM)
        tot_f_N = tot_f_N/(div_width*dz*tot_lines)
        
    return np.log10(center), tot_f_N, b_params, np.log10(n_vals), fit_results, tau


