def get_flux_power_1D(rs, window=False, tau_thresh=1e6, mean_flux_desired=None, elem="H", ion=1, line=1215):
    #filtering for DLAs sets tau_thresh=1e6 and it will remove power on the low k end
    """Get the power spectrum of (variations in) the flux along the line of sight.
    This is: P_F(k_F) = <d_F d_F>
             d_F = e^-tau / mean(e^-tau) - 1
    Arguments:
        mean_flux_desired: if not None, the spectral optical depths will be rescaled
            to match the desired mean flux.
        window: if True, the flux power spectrum is divided by the window function for the pixel width.
                This interacts poorly with mean flux rescaling.
        tau_thresh: sightlines with a total optical depth greater than this value are removed before mean flux rescaling.
    Output:
        kf, avg_flux_pwoer - the k values and the corresponding calculated power spectrum
    """
    tau = rs.get_tau(elem, ion, line)
    if tau_thresh is not None:
        tau = rs._filter_tau(tau, tau_thresh=tau_thresh)
    (kf, avg_flux_power) = fstat.flux_power(tau, rs.vmax, spec_res=rs.spec_res, window=window, mean_flux_desired=mean_flux_desired)

    return kf, avg_flux_power


def get_flux_power_1D_UVBcorr(rs, window=False, tau_thresh=1e6, UVBcorr=1, elem="H", ion=1, line=1215):
    """Same as get_flux_power_1D but with the ability to rescale the photionizng rate post-processing.
    
    New parameter:
        UVBcorr - value by which to rescale the HI photoionizing rate post-processing
    """
    tau = rs.get_tau(elem, ion, line)
    if tau_thresh is not None:
        tau = rs._filter_tau(tau, tau_thresh=tau_thresh)
    taucorr = tau/UVBcorr
    (kf, avg_flux_power) = fstat.flux_power(taucorr, rs.vmax, spec_res=rs.spec_res, window=window)

    return kf, avg_flux_power

def get_flux_power_1D_taueffcorr(rs, rsmatch, window=False, tau_thresh=1e6, elem="H", ion=1, line=1215):
    """Same as get_flux_power_1D but with the ability to rescale to match the same mean transmitted flux as another file.
    
    New parameter:
        rsmatch - the spectral file you want to match the same mean flux of
    """
    tau = rs.get_tau(elem, ion, line)
    if tau_thresh is not None:
        tau = rs._filter_tau(tau, tau_thresh=tau_thresh)
    mean_flux_desired = rsmatch.get_mean_flux(tau_thresh=tau_thresh)
    (kf, avg_flux_power) = fstat.flux_power(tau, rs.vmax, spec_res=rs.spec_res, window=window, mean_flux_desired=mean_flux_desired)

    return kf, avg_flux_power
